export const copy = { pt, en, es };
export function apiError(
  code: unknown,
  locale: Locale,
  fallback: "startError" | "sendError" = "startError",
): string {
  const keys: Record<string, keyof typeof pt> = {
    name_required: "nameError",
    email_invalid: "emailError",
    phone_invalid: "phoneError",
    identity_invalid: "identityError",
  };
  return copy[locale][keys[String(code)] || fallback];
}
